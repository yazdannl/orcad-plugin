#!/usr/bin/env python3
"""Build the single-file orcad.py release.

OrcaSlicer's Plugin Hub accepts one .py file, so the compiled frontend
(frontend/dist/index.html) and the OpenSCAD backend package (openscad/, with
the vendored Gridfinity library) are embedded into orcad.py as compressed,
deterministic blobs. When the package is installed as a folder, orcad.py
prefers the files beside it instead.

    python3 packaging/bundle.py            # build the frontend and embed it + the backend
    python3 packaging/bundle.py --check    # fail if orcad.py or dist/ is stale (CI)
    python3 packaging/bundle.py --release  # build, embed, then run all tests
"""
from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "orcad.py"
FRONTEND = ROOT / "frontend"
DIST = FRONTEND / "dist" / "index.html"
# The 3D viewer, built beside the page so three.js stays out of it.
VIEWPORT = FRONTEND / "dist" / "viewport.js"
THUMBS = FRONTEND / "src" / "thumbs"
BACKEND = ROOT / "openscad"
AI_BACKEND = ROOT / "ai"
ICON = ROOT / "assets" / "orcad-icon.png"
# OrcaSlicer builds the tab from one HTML string and hands it to the webview in
# one go (WebView2 NavigateToString), which refuses content above 2 MB and is
# unreliable well before that. Keep the page far below it: the catalog, the
# previews and the viewer are fetched from the plugin at runtime instead.
MAX_PAGE_BYTES = 1024 * 1024
REGIONS = {
    "backend": ("# BEGIN EMBEDDED OPENSCAD BACKEND", "# END EMBEDDED OPENSCAD BACKEND", "_EMBEDDED_BACKEND"),
    "frontend": ("# BEGIN BUNDLED FRONTEND", "# END BUNDLED FRONTEND", "_EMBEDDED_FRONTEND"),
    "icon": ("# BEGIN EMBEDDED TAB ICON", "# END EMBEDDED TAB ICON", "_EMBEDDED_ICON"),
}
_SKIP = re.compile(r"(^|/)(__pycache__|\.pytest_cache)(/|$)|\.py[co]$")


def _blob(data: bytes) -> str:
    return base64.b64encode(gzip.compress(data, compresslevel=9, mtime=0)).decode("ascii")


def backend_archive(viewport_js: Path | None = None) -> bytes:
    """Deterministic zip of everything the plugin ships: the OpenSCAD backend,
    the AI backend, the prebuilt model previews and the 3D viewer chunk.

    The bytes must not depend on the build host: the committed blob is verified
    on Linux, Windows and macOS, and ZipInfo records the creating platform.
    """
    viewer = viewport_js if viewport_js is not None else VIEWPORT
    files: dict[str, Path] = {}
    for package in (BACKEND, AI_BACKEND):
        for path in package.rglob("*"):
            name = path.relative_to(ROOT).as_posix()
            if path.is_file() and not _SKIP.search(name):
                files[name] = path
    for path in sorted(THUMBS.glob("*.png")):
        files[f"thumbs/{path.name}"] = path
    if viewer.is_file():
        files["viewport.js"] = viewer
    # The mesh fast path is a compiled library, so its source ships beside it:
    # the C is what the binaries were built from (native/build.py, checked in CI).
    for path in sorted((ROOT / "native").glob("*")):
        if path.is_file() and path.suffix in (".c", ".h", ".md"):
            files[f"native/{path.name}"] = path
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        manifest = _manifest(files)
        for name, data in [("PAYLOAD.md", manifest), *((name, files[name].read_bytes()) for name in sorted(files))]:
            info = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
            info.create_system = 3  # Unix; ZipInfo would otherwise record the build host
            info.external_attr = 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data)
    return buffer.getvalue()


def _manifest(files: dict[str, Path]) -> bytes:
    """A plain-text index of the archive, so it can be read without unpacking it.

    The release is one file with a compressed payload, which is what OrcaSlicer's
    installer accepts but also what makes its contents opaque to a reader. This
    list gives every member's size and SHA-256 up front.
    """
    lines = ["# OrcaCAD plugin payload", "",
             "Generated by packaging/bundle.py; every line describes one member of this",
             "archive, sorted by path so a rebuild is byte-identical. Source files are text.",
             "", "| path | bytes | sha256 |", "| --- | ---: | --- |"]
    for name in sorted(files):
        data = files[name].read_bytes()
        lines.append(f"| `{name}` | {len(data)} | `{hashlib.sha256(data).hexdigest()}` |")
    lines.append("")
    return "\n".join(lines).encode("utf-8")


def render_target(text: str, frontend_html: str) -> str:
    values = {"backend": _blob(backend_archive()), "frontend": _blob(frontend_html.encode("utf-8")),
              "icon": _blob(ICON.read_bytes())}
    for key, (begin, end, variable) in REGIONS.items():
        pattern = re.compile(re.escape(begin) + r"\n.*?\n" + re.escape(end), re.S)
        if not pattern.search(text):
            raise SystemExit(f"{TARGET.name}: missing region {begin!r}")
        replacement = f'{begin}\n{variable} = "{values[key]}"\n{end}'
        text = pattern.sub(lambda _, r=replacement: r, text, count=1)  # a function: blobs are not regex templates
    return text


def build_frontend(out_dir: Path | None = None) -> None:
    if not (FRONTEND / "node_modules").is_dir():
        raise SystemExit("frontend dependencies are missing; run `cd frontend && npm ci` first")
    env = dict(os.environ)
    if out_dir is not None:  # build the page and the viewer into a scratch directory
        env["ORCAD_OUT_DIR"] = str(out_dir)
    subprocess.run(["npm", "run", "build"], cwd=FRONTEND, check=True,
                   shell=sys.platform == "win32", env=env)


def run_tests() -> None:
    subprocess.run([sys.executable, "-m", "pytest", "-q", "tests"], cwd=ROOT, check=True)
    subprocess.run(["npm", "test"], cwd=FRONTEND, check=True, shell=sys.platform == "win32")


def embedded_blob(text: str, variable: str) -> bytes:
    """Decode the committed blob of one region, e.g. _EMBEDDED_BACKEND."""
    match = re.search(rf'^{variable} = "([^"]*)"$', text, re.M)
    if not match:
        raise SystemExit(f"{TARGET.name}: missing {variable}")
    return gzip.decompress(base64.b64decode(match.group(1)))


def archive_members(data: bytes) -> dict[str, str]:
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return {name: hashlib.sha256(archive.read(name)).hexdigest() for name in archive.namelist()}


def stale_members(committed: dict[str, str], fresh: dict[str, str]) -> list[str]:
    return sorted(name for name in committed.keys() | fresh.keys() if committed.get(name) != fresh.get(name))


def crlf_files() -> list[str]:
    """Embedded files whose working-tree CRLF line endings .gitattributes hides.

    `* text=auto eol=lf` makes git call a CRLF working tree clean and commit LF,
    but the bundle embeds the bytes on disk: a blob built here then differs from
    the one CI builds from a fresh checkout, which reports the release as stale.
    """
    try:
        listed = subprocess.run(["git", "ls-files", "--eol", "--", BACKEND.name, AI_BACKEND.name],
                                cwd=ROOT, capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):  # a source tree without git
        return []
    return [line.rsplit("\t", 1)[-1] for line in listed.splitlines() if "w/crlf" in line or "w/mixed" in line]


def check() -> int:
    with tempfile.TemporaryDirectory() as directory:
        out_dir = Path(directory)
        build_frontend(out_dir)
        fresh = (out_dir / "index.html").read_text(encoding="utf-8")
        fresh_archive = backend_archive(out_dir / "viewport.js")
    problems = []
    if len(fresh.encode("utf-8")) > MAX_PAGE_BYTES:
        problems.append(f"the built page is {len(fresh.encode('utf-8')) // 1024} KB, over the {MAX_PAGE_BYTES // 1024} KB "
                        "page budget; the host hands it to the webview in one string and stops rendering above 2 MB "
                        "(see the notes in frontend/src/catalog.js)")
    crlf = crlf_files()
    for name in crlf:
        print(f"error: {name} has CRLF in the working tree, which git hides but the embedded blob keeps; "
              "rewrite it with LF line endings and rebuild", file=sys.stderr)
    if not DIST.is_file() or DIST.read_text(encoding="utf-8") != fresh:
        problems.append("frontend/dist/index.html is stale")
    current = TARGET.read_text(encoding="utf-8")
    if render_target(current, fresh) != current:
        detail = []
        try:
            changed = stale_members(archive_members(embedded_blob(current, "_EMBEDDED_BACKEND")),
                                    archive_members(fresh_archive))
        except (KeyError, zipfile.BadZipFile) as error:
            detail = [f"backend blob unreadable: {error}"]
        else:
            detail = [f"{len(changed)} backend file(s) differ: {', '.join(changed[:5]) or 'none by content'}"]
            detail.append("frontend blob differs" if _blob(fresh.encode("utf-8")) !=
                          _blob(embedded_blob(current, "_EMBEDDED_FRONTEND")) else "frontend blob matches")
            detail.append("icon blob differs" if _blob(ICON.read_bytes()) !=
                          _blob(embedded_blob(current, "_EMBEDDED_ICON")) else "icon blob matches")
        problems.append("orcad.py embedded blobs are stale: " + "; ".join(detail))
    for problem in problems:
        print(f"error: {problem}; run `python3 packaging/bundle.py`", file=sys.stderr)
    return 1 if problems or crlf else 0


def write() -> None:
    build_frontend()
    TARGET.write_text(render_target(TARGET.read_text(encoding="utf-8"), DIST.read_text(encoding="utf-8")),
                      encoding="utf-8")
    shutil.rmtree(BACKEND / "__pycache__", ignore_errors=True)
    thumbs = len(list(THUMBS.glob("*.png")))
    print(f"embedded {DIST.relative_to(ROOT)} ({DIST.stat().st_size // 1024} KB), {thumbs} model previews, "
          f"{VIEWPORT.relative_to(ROOT)}, openscad/, ai/ and the tab icon into {TARGET.name} "
          f"({TARGET.stat().st_size // 1024} KB)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="verify generated files without writing")
    mode.add_argument("--release", action="store_true", help="build, embed and run every test suite")
    args = parser.parse_args()
    if args.check:
        return check()
    write()
    if args.release:
        run_tests()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
